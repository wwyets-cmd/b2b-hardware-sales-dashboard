def detect_brand(name):
    """返回标准品牌名；无品牌返回 None。"""
    name = str(name)
    for label, kws, require, exclude in BRAND_RULES:
        if not any(k in name for k in kws):
            continue
        if require is not None and not require.search(name):
            continue
        if exclude is not None and exclude.search(name):
            continue
        return label
    return None


